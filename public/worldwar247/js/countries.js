function flagFromCode(code) {
  let out = "";
  for (const ch of code) out += String.fromCodePoint(0x1f1e6 + ch.charCodeAt(0) - 65);
  return out;
}

export const WW_COUNTRIES = RAW.map((row, i) => ({
  id: i + 1,
  code: row[0],
  name: row[1],
  flag: flagFromCode(row[0]),
  c1: row[2],
  c2: row[3],
  perk: WW_PERK_NAMES[row[4]],
  // Deterministic Elo seed spread; converges to true skill after a few tournaments.
  elo: Math.round(1500 - i * 1.7 + ((i * 37) % 23)),
}));

export const WW_COUNTRY_BY_CODE = Object.fromEntries(WW_COUNTRIES.map((c) => [c.code, c]));

export function countryName(code) {
  const c = WW_COUNTRY_BY_CODE[code];
  return c ? c.name : code;
}

export function countryFlag(code) {
  const c = WW_COUNTRY_BY_CODE[code];
  return c ? c.flag : "🏳️";
}
